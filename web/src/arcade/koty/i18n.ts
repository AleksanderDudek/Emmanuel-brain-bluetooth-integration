export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` pests: 1 szkodnik, 3 szkodniki, 5 szkodników; 1 pest, 2 pests; 1 Schädling; 1 skadedjur. */
export const unit = (n: number): string => bare('pests', n);

/** "12 szkodników" (a no-break space between the number and the word). */
export const pestsText = (n: number): string => t('pests', { n });
