/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` demons: 1 demon, 3 demony, 5 demonów; 1 demon, 2 demons. */
export const unit = (n: number): string => bare('demons', n);

/** "12 demonów" (a no-break space between the number and the word). */
export const demons = (n: number): string => t('demons', { n });

