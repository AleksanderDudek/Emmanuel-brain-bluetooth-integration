export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` fruits: 1 owoc, 3 owoce, 5 owoców; fruits; Früchte; frukter. */
export const unit = (n: number): string => bare('fruits', n);

/** A fruit's name ("cierpliwość", "patience", "Geduld", "tålamod"). */
export const fruitName = (f: FruitId): string => t(`fruit.${f}.name` as Key);

/** A name with its first letter capital (a label begins with it). */
export const cap = (s: string): string => (s ? s[0].toLocaleUpperCase(lang) + s.slice(1) : s);

/** The fruits ripened, as the summary says them: three names, then "+N". */
export function fruitList(list: readonly FruitId[]): string {
  const names = list.slice(0, 3).map(fruitName);
  const more = list.length - names.length;
  return more > 0 ? `${names.join(', ')} ${t('more', { n: more })}` : names.join(', ');
}

/** The breath in words: "wdech 4 s, wydech 6 s". */
export function breathWords(p: BreathPattern): string {
  return BREATH_PHASES.filter(k => p[k] > 0).map(k => t('br.part', { what: t(`br.${k}` as Key), n: p[k] })).join(', ');
}

/** The guide's word for a phase of the breath. */
export const phaseWord = (k: keyof BreathPattern): string => t(`hud.${k}` as Key);

/** The narrator's lines for a moment. */
export const linesOf = (m: Moment): readonly string[] =>
  Array.from({ length: LINE_COUNT }, (_, i) => t(`say.${m}.${i + 1}` as Key));

/** Every fruit's texts exist (the tests read it). */
export const FRUIT_KEYS = FRUITS.flatMap(f => ['name', 'r1', 'r2', 'task'].map(k => `fruit.${f}.${k}`));
