export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own (the headline's unit, the word under the score). */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` pairs: 1 para, 3 pary, 5 par; 1 pair, 2 pairs; 1 Paar, 2 Paare; 1 par. */
export const unit = (n: number): string => bare('pairs', n);

/** A name from inside a sentence as a label of its own: "owce" → "Owce", "a well" stays a label via its short key. */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);
