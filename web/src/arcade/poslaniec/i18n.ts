export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

let grouping: Intl.NumberFormat | null = null;

/** A whole number grouped in thousands from four digits on, with no-break spaces ("1 234"). */
export function grouped(v: number): string {
  grouping ??= new Intl.NumberFormat(locale, { maximumFractionDigits: 0, useGrouping: 'always' } as unknown as Intl.NumberFormatOptions);
  return grouping.format(Math.round(v)).replace(/[\s ]/g, ' ');
}

/** A distance for the eye: "860 m", "12 400 m" (a no-break space before the unit). */
export function metres(m: number): string {
  return `${grouped(Math.max(0, Math.round(m)))} m`;
}

/** A distance in kilometres, one decimal ("1,2 km"). */
export const km = (m: number): string => `${fmtNum(Math.max(0, m) / 1000, 1)} km`;

/** A road distance: metres under 1 km, else kilometres. */
export const road = (m: number): string => (m < 1000 ? metres(m) : km(m));
