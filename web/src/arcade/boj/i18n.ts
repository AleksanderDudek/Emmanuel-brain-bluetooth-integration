export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` landed strikes: 1 cios, 3 ciosy, 5 ciosów; strikes; Treffer; träffar. */
export const unit = (n: number): string => bare('strikes', n);

/** The lines of a coach moment: `say.<moment>.1`, `.2`… in this page load's language. */
export function linesOf(moment: string): string[] {
  const out: string[] = [];
  for (let i = 1; i <= 9; i++) {
    const k = `say.${moment}.${i}` as Key;
    if (!(k in pl)) break;
    out.push(t(k));
  }
  return out;
}
