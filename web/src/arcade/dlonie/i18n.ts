export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` flames: 1 płomyk, 3 płomyki, 5 płomyków. */
export const unit = (n: number): string => bare('flames', n);
/** "1 240 płomyków" (a no-break space between the number and the word). */
export const flameText = (n: number): string => t('flames', { n });

/** The name of the one prayed for, as shown: the player's name, or someone dear, me, the world. */
export function whoName(p: Pick<DlonieProgress, 'names'>, who: Who): string {
  if (who.kind === 'name') return p.names[who.i]?.name ?? t('who.dear');
  return t(`who.${who.kind}` as 'who.dear');
}

/** A place's name (lower case, as in a sentence). */
export const placeName = (place: HurtPlace): string => t(`place.${place}` as 'place.head');
/** A place's name with a capital (a label of its own). */
export const placeLabel = (place: HurtPlace): string => { const s = placeName(place); return s.charAt(0).toLocaleUpperCase() + s.slice(1); };

/** The narrator's lines for a moment (a mouse hears "click" where a finger hears "tap", where a line says so). */
export function linesOf(m: Moment, mouse = false): string[] {
  const out: string[] = [];
  for (let i = 1; i <= 2; i++) {
    const key = `say.${m}.${i}` as Key;
    const mk = `${key}.mouse` as Key;
    out.push(mouse && mk in CATALOGS.pl ? t(mk) : t(key));
  }
  return out;
}
