export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for a word set beside a number drawn on its own (the jar count's unit). */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` jars: 1 dzban, 3 dzbany, 5 dzbanów; 1 jar, 2 jars. */
export const unit = (n: number): string => bare('jars', n);

/** A name from inside a sentence as a label of its own: "palma daktylowa" → "Palma daktylowa". */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);
