export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` pieces: 1 część, 3 części; 1 piece, 2 pieces; 1 Teil, 2 Teile; 1 del, 2 delar. */
export const unit = (n: number): string => bare('pieces', n);

/** "12 części" (a no-break space between the number and the word). */
export const piecesText = (n: number): string => t('pieces', { n });
