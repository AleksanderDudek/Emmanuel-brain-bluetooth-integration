/** A plural text without its number, for words set beside a number drawn on its own (the headline's unit). */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` points: pkt; point/points; Punkt/Punkte; poäng. */
export const unit = (n: number): string => bare('pts', n);

/** A name from inside a sentence as a label of its own: "mały pasterz" → "Mały pasterz". */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);
