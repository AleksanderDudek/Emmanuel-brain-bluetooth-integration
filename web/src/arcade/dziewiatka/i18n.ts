export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n`: 1 uciszony, 3 uciszone, 5 uciszonych; hushed; besänftigt; 1 tystad, 2 tystade. */
export const unit = (n: number): string => bare('hushed', n);

/** "12 uciszonych" (a no-break space between the number and the word). */
export const hushed = (n: number): string => t('hushed', { n });
