export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural word without its number ("sykli"), for the score corner's unit. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

/** A name from inside a sentence as a label of its own: "dzban na wodę" → "Dzban na wodę". */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);

/** A whole number the language's way (1 240 / 1,240). */
export const fmtInt = (v: number): string => fmtNum(Math.round(v), 0);

/** A customer's words in the language's quotation marks. */
export function quote(s: string): string {
  const [a, b] = lang === 'pl' ? ['„', '”'] : lang === 'de' ? ['„', '“'] : lang === 'sv' ? ['”', '”'] : ['“', '”'];
  return `${a}${s}${b}`;
}

