export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

/** A name from inside a sentence as a label of its own: "dzban na wodę" → "Dzban na wodę". */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);

/** A height as the language writes it: one decimal ("12,4"), or none for a whole headline. */
export const fmtCm = (v: number, whole = false): string => fmtNum(whole ? Math.round(v) : Math.round(v * 10) / 10, whole ? 0 : 1);

/** "12,4 cm" (one decimal, the language's comma), "12 cm" when `whole`. */
export const cmText = (v: number, whole = false): string => t('cm', { n: fmtCm(v, whole) });

/** "88%" / "88 %" for a share 0..1. */
export const pctText = (share: number): string => t('pct', { n: Math.round(share * 100) });
