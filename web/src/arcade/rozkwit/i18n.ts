// ── what Rozkwit copies from the games it borrows ────────────────
type Words = Record<Lang, Record<string, Msg>>;
const blank = (): Words => Object.fromEntries(LANGS.map(l => [l, {} as Record<string, Msg>])) as Words;

/** The names of the parts on Każdy włos's pictures (`part.wlosy_<p>`). */
function hairParts(): Words {
  const out = blank();
  for (const theirs of Object.values(HAIR_SCENES)) {
    for (const lb of HAIR_SCENE[theirs].labels) {
      for (const l of LANGS) {
        const cat = HAIR_WORDS[l] as Readonly<Record<string, Msg | undefined>>;
        const m = cat[`part.${lb.part}`] ?? (HAIR_WORDS.pl as Readonly<Record<string, Msg | undefined>>)[`part.${lb.part}`];
        if (m !== undefined) out[l][`part.${hairPart(lb.part)}`] = m;
      }
    }
  }
  return out;
}

/** Each meditation's everyday step and the person's looks, in the source games' words (the looks are Nowe siły's). */
function copiedLines(): Words {
  const out = blank();
  for (const [m, c] of Object.entries(CARE)) {
    const w = copied(c.lib, c.key);
    for (const l of LANGS) out[l][`med.${m}.care`] = w[l];
  }
  for (const key of LOOK_KEYS) {
    const w = copied(SILY, key);
    for (const l of LANGS) out[l][key] = w[l];
  }
  return out;
}

/** Rozkwit's own words, then the copied ones (the sources' polish reaches them by itself). */
export const OWN: Readonly<Record<Lang, Catalog<Key>>> = { pl, en, de, sv };
export const WORDS: Readonly<Record<Lang, Catalog<string>>> = mergeWords(OWN, borrowedParts(Object.values(BORROWS)), hairParts(), copiedLines());
