export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit: pkt, pts, Pkt., p. */
export const unit = (n: number): string => bare('pts', n);

/** "1 240 pkt" (a no-break space between the number and the unit). */
export const pts = (n: number): string => format(pick(CATALOGS[lang].pts, n), { n: fmtNum(Math.round(n)) });

/** One of a moment's lines (`bubo.<moment>.1..3`), picked by `k`. */
export function line(moment: string, k: number): string {
  const key = `bubo.${moment}.${(Math.abs(Math.floor(k)) % 3) + 1}` as Key;
  return key in CATALOGS.pl ? t(key) : '';
}
