export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own (the headline's unit, "łodzie w porcie" under the score). */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` boats: 1 łódź, 3 łodzie, 5 łodzi; 1 boat, 2 boats. */
export const unit = (n: number): string => bare('boats', n);

/** The blind Konwój's reveal: "Z daleka dopłynęły 3 statki", the verb agreeing too. */
export const farShips = (n: number): string => (n > 0 ? t('far.ships', { n }) : t('far.none'));

/** A name from inside a sentence as a label of its own: "chata rybacka" → "Chata rybacka". */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);

/** A night's name ("Mgła") and its goal in words ("Znajdź we mgle 3 łodzie"). */
export const nightName = (kind: 'powroty' | 'mgla' | 'flotylla' | 'ratunek' | 'szkwal'): string => t(`night.${kind}`);
export const goalText = (kind: 'powroty' | 'mgla' | 'flotylla' | 'ratunek' | 'szkwal', n: number): string => t(`goal.${kind}`, { n });
export const storyText = (kind: 'powroty' | 'mgla' | 'flotylla' | 'ratunek' | 'szkwal'): string => t(`story.${kind}`);
