export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` Zmory: 1 zmora, 3 zmory, 5 zmór; 1 nightmare; 1 Albtraum, 2 Albträume; 1 mardröm. */
export const unit = (n: number): string => bare('zmory', n);

/** "12 zmór" (a no-break space between the number and the word). */
export const zmory = (n: number): string => t('zmory', { n });
export const feathers = (n: number): string => t('feathers', { n });
