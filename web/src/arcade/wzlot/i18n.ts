export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/\s{2,}/g, ' ').trim();
}

let grouping: Intl.NumberFormat | null = null;

/**
 * A whole number grouped in thousands from four digits on ("1 234", "1,234", "1.234"): Polish
 * Intl leaves four digits ungrouped, which reads poorly next to "12 400".  A space-like group
 * separator becomes a no-break space, so the canvas never breaks a number.
 */
export function grouped(v: number): string {
  // 'always' is ES2023's (older engines read it as true: the locale's own grouping)
  grouping ??= new Intl.NumberFormat(locale, { maximumFractionDigits: 0, useGrouping: 'always' } as unknown as Intl.NumberFormatOptions);
  return grouping.format(Math.round(v)).replace(/[\s\u202f]/g, '\u00a0');
}

/** A distance for the eye: "860 m", "12 400 m"; from 100 km on "123 km" (a no-break space before the unit). */
export function metres(m: number): string {
  const v = Math.max(0, Math.round(m));
  return v < 100_000 ? `${grouped(v)}\u00a0m` : `${grouped(v / 1000)}\u00a0km`;
}

/** A distance in kilometres, one decimal ("1,2 km", "1.2 km" in English). */
export const km = (m: number): string => `${fmtNum(Math.max(0, m) / 1000, 1)} km`;

/** A name from inside a sentence as a label of its own: "puch" → "Puch". */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);
