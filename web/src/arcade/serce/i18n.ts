export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` lights: 1 światło, 3 światła, 5 świateł; lights; Lichter; ljus. */
export const unit = (n: number): string => bare('lights', n);

/** "12 świateł" (a no-break space between the number and the word). */
export const lightsText = (n: number): string => t('lights', { n });

/** The breath in words, its phases of some length in order: "wdech 5 s, wydech 5 s". */
export function breathWords(p: BreathPattern): string {
  return BREATH_PHASES.filter(k => p[k] > 0).map(k => t('br.part', { what: t(`br.${k}` as Key), n: p[k] })).join(', ');
}

/** A word with its first letter capitalised (the breath's phase on the guide). */
export const cap = (s: string): string => (s ? s[0].toLocaleUpperCase(lang) + s.slice(1) : s);
