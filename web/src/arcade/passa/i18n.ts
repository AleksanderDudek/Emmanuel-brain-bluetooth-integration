export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` wins: 1 zwycięstwo, 3 zwycięstwa, 5 zwycięstw; win(s); Sieg(e); seger, segrar. */
export const unit = (n: number): string => bare('wins', n);

/** The lines of a narrator's moment: `say.<what>.1`, `.2`… in this page load's language. */
export function linesOf(what: string): string[] {
  const out: string[] = [];
  for (let i = 1; i <= 9; i++) {
    const k = `say.${what}.${i}` as Key;
    if (!(k in pl)) break;
    out.push(t(k));
  }
  return out;
}

/** The street's sign: "Dzień passy: 5" (the first day its own words). */
export const signText = (days: number): string => (days <= 1 ? t('sign.first') : t('sign.days', { n: days }));
