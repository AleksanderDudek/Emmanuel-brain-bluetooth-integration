/**
 * Złota passa, round 25 (DESIGN.md §29): the moments of each age group's day — the sets (what each moment is: its kind,
 * its small picture, its part of the day, its place in the film, the groups it fits, a sense moment's sense) and their
 * words in Polish, the source.  The contract is life.ts; English, German and Swedish are in life-sets.{en,de,sv}.ts
 * with the same keys.
 *
 *   <id>.what       the card's line: what happens (≤ 64 characters)
 *   <id>.win.<n>    the gold side, n from 1: a joy, a sense and a given moment one (the thanks); a snag two or three
 *                   honest reframes; a heavy one two or three humble hopes ("not yet — I trust" is the sim's)  (≤ 52)
 *   <id>.guide.<n>  a sense moment's 2–4 guide lines, one after another through its mini session — present tense, the
 *                   second person, gentle and concrete: where to put the attention next  (≤ 70)
 *   <id>.without    a given moment's "imagine without" line for its rest (mental subtraction)  (≤ 110)
 *
 * Ids are `<age|all>.<slug>`; `all.*` is the pool that fits every group (`ages: []`).  Each group has a full day of its
 * own life: a teen's school bus, break time and a song in the earphones (11–19 are children and youth: a heavy moment
 * for them is only a hurt at school, at home or in a friendship, with a trusted adult in view); a student's rented
 * room, jars from home and a shift behind a counter; a young parent's night, the nursery's floor and the office; the
 * middle years' school runs, the garden and a parent who forgets; the 50+ — still at work or retired — the allotment,
 * the pharmacy, the noon bells and a grandchild's voice.
 *
 * The words keep the house rules: the player is never gendered in Polish (present tense, nouns, "mogę", "uczę się";
 * no "sam/sama"); the address is capitalised ("Ty", "Twój"); no verse paraphrased (the verses stay in content.ts); a
 * snag's wins are honest reframes, never "nothing bad happened" or "the universe"; a heavy moment's hopes are humble,
 * never a promise; the given moments' "without" lines picture a real absence gently (what many lived or still live),
 * never a threat.
 */
import type { Age } from '../kit/ages';
import type { LifeKind, LifeMotif, LifeSet, Place, Sense } from './life';
import type { DayPart, Motif } from './moments';

type Pic = Motif | LifeMotif;

interface Draft {
  slug: string;
  kind: LifeKind;
  motif: Pic;
  part: DayPart;
  place: Place;
  sense?: Sense;
  what: string;
  wins: readonly string[];
  guide?: readonly string[];
  without?: string;
}

const joy = (slug: string, motif: Pic, part: DayPart, place: Place, what: string, win: string): Draft =>
  ({ slug, kind: 'joy', motif, part, place, what, wins: [win] });
const snag = (slug: string, motif: Pic, part: DayPart, place: Place, what: string, wins: readonly string[]): Draft =>
  ({ slug, kind: 'snag', motif, part, place, what, wins });
const heavy = (slug: string, motif: Pic, part: DayPart, place: Place, what: string, hopes: readonly string[]): Draft =>
  ({ slug, kind: 'heavy', motif, part, place, what, wins: hopes });
const sense = (slug: string, s: Sense, motif: Pic, part: DayPart, place: Place, what: string, guide: readonly string[], win: string): Draft =>
  ({ slug, kind: 'sense', sense: s, motif, part, place, what, guide, wins: [win] });
const given = (slug: string, motif: Pic, part: DayPart, place: Place, what: string, without: string, win: string): Draft =>
  ({ slug, kind: 'given', motif, part, place, what, without, wins: [win] });

