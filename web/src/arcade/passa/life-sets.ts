const GROUPS: ReadonlyArray<readonly [Age | 'all', readonly Draft[]]> = [
  ['all', ALL], ['teen', TEEN], ['young', YOUNG], ['adult', ADULT], ['mid', MID], ['senior', SENIOR],
];

/** The words of a draft under its id (`<id>.what`, `<id>.win.<n>`, `<id>.guide.<n>`, `<id>.without`). */
function wordsOf(id: string, d: Draft, out: Record<string, string>): void {
  out[`${id}.what`] = d.what;
  d.wins.forEach((w, i) => { out[`${id}.win.${i + 1}`] = w; });
  d.guide?.forEach((g, i) => { out[`${id}.guide.${i + 1}`] = g; });
  if (d.without !== undefined) out[`${id}.without`] = d.without;
}

const sets: LifeSet[] = [];
const words: Record<string, string> = {};
for (const [group, drafts] of GROUPS) for (const d of drafts) {
  const id = `${group}.${d.slug}`;
  const ages: readonly Age[] = group === 'all' ? [] : [group];
  const s: LifeSet = { id, kind: d.kind, motif: d.motif, part: d.part, place: d.place, ages };
  if (d.sense) s.sense = d.sense;
  sets.push(s);
  wordsOf(id, d, words);
}

/** Every set moment of the day, the shared pool first, then each group's in the order of its day. */
export const LIFE_SETS: readonly LifeSet[] = sets;

