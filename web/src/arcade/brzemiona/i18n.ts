/** A kind's noun ("choroba"). */
export const kindName = (k: KindId): string => t(`kind.${k}` as Key);

/** Who an item is, as a label: the name as written, "Ja", "Chorzy", "Cały świat". */
export function whoName(it: Item): string {
  if (it.who === 'person') return it.name;
  if (it.who === 'me') return t('who.me');
  if (it.who === 'world') return t('who.world');
  return t(`who.${it.kind ?? 'illness'}` as Key);
}

/** A circle's name in the summary ("cały świat"). */
export const circleName = (c: Circle): string => t(`circle.${c}` as Key);

/** Who is prayed for in a circle, as the band's label: the one, all who carry it, the whole world. */
export function circleLabel(it: Item, c: Circle): string {
  if (c === 'world') return t('who.world');
  if (c === 'many') return t(`many.${it.kind ?? 'any'}` as Key);
  return whoName(it);
}

/** The address of a burden (its first circle) or of a widening. */
export function addressOf(it: Item, c: Circle, widening: boolean): string {
  if (widening && c === 'many') return t('call.many', { all: t(`all.${it.kind ?? 'any'}` as Key) });
  if (widening && c === 'world') return t('call.wide');
  if (it.who === 'world' || c === 'world') return t('call.world');
  if (it.who === 'person') return it.kind ? t('call.personKind', { name: it.name, what: t(`what.${it.kind}` as Key) }) : t('call.person', { name: it.name });
  if (it.who === 'me') return it.kind ? t('call.meKind', { what: t(`what.${it.kind}` as Key) }) : t('call.me');
  if (c === 'many') return t('call.many', { all: t(`all.${it.kind ?? 'any'}` as Key) });
  return t('call.kind', { some: t(`some.${it.kind ?? 'illness'}` as Key) });
}

/** The prayer of the exchange on the breath's phase, by circle (the light-only words in that variant). */
export function prayerOf(phase: keyof BreathPattern, c: Circle, lightOnly: boolean): string {
  if (lightOnly) {
    if (phase === 'in') return t('light.in');
    if (phase === 'out') return t(c === 'world' ? 'light.outWorld' : 'light.out');
    return t('light.hold');
  }
  if (phase === 'in') return t(c === 'world' ? 'pray.inWorld' : c === 'many' ? 'pray.inMany' : 'pray.in');
  if (phase === 'out') return t(c === 'world' ? 'pray.outWorld' : c === 'many' ? 'pray.outMany' : 'pray.out');
  return t(phase === 'holdIn' ? 'pray.holdIn' : 'pray.holdOut');
}
