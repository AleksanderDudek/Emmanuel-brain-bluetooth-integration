export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` burdens: 1 brzemię, 3 brzemiona, 5 brzemion; burdens; Lasten; bördor. */
export const unit = (n: number): string => bare('burdens', n);

/** "4 brzemiona" (a no-break space between the number and the word). */
export const burdensText = (n: number): string => t('burdens', { n });

/** The breath in words, its phases of some length in order: "wdech 5 s, wydech 5 s". */
export function breathWords(p: BreathPattern): string {
  return BREATH_PHASES.filter(k => p[k] > 0).map(k => t('br.part', { what: t(`br.${k}` as Key), n: p[k] })).join(', ');
}

/** The guide's word for a phase of the breath ("Wdech", "Zatrzymaj", "Wydech", "Bezdech"). */
export const phaseWord = (k: keyof BreathPattern): string => t(`hud.${k}` as Key);

/** The narrator's variants for a moment. */
export function linesOf(m: Moment): string[] {
  const out: string[] = [];
  for (let i = 1; i <= LINE_COUNT; i++) out.push(t(`say.${m}.${i}` as Key));
  return out;
}
