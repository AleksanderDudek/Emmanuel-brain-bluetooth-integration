/** A count's word without its number (the headline's unit): "połączeń", "connections". */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` connections: 1 połączenie, 3 połączenia, 5 połączeń; 1 connection; 1 Verbindung; 1 koppling. */
export const unit = (n: number): string => bare('conn', n);

/** The song's verse lines in a language (the player may be built for a page in any of the four). */
export const verseLines = (l: keyof typeof CATALOGS): string[] =>
  (['song.a1', 'song.a2', 'song.a3', 'song.a4', 'song.b1', 'song.b2', 'song.b3', 'song.b4'] as const).map(k => CATALOGS[l][k] as string);
