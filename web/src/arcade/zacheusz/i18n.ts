export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/[\s ]{2,}/g, ' ').replace(/^[\s ]+/, '').trim();
}

/** The headline's unit for a count: 1 denar, 2 denary, 5 denarów (denarius/denarii, Denar/Denare, denar/denarer). */
export const unit = (n: number): string => bare('denarii', Math.round(n));

let grouping: Intl.NumberFormat | null = null;

/** A whole number grouped in thousands from four digits on, with a no-break space as the separator. */
export function grouped(v: number): string {
  grouping ??= new Intl.NumberFormat(locale, { maximumFractionDigits: 0, useGrouping: 'always' } as unknown as Intl.NumberFormatOptions);
  return grouping.format(Math.round(v)).replace(/[\s ]/g, ' ');
}

/** A name from inside a sentence as a label of its own: "srebrne" → "Srebrne". */
export const cap = (s: string): string => s.charAt(0).toLocaleUpperCase(locale) + s.slice(1);
