export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit for `n` people fed: 1 nakarmiony, 5 nakarmionych; 1 fed. */
export const unit = (n: number): string => bare('fed', n);

/** "12 nakarmionych" (a no-break space between the number and the word). */
export const fed = (n: number): string => t('fed', { n });

/** "4 kosze". */
export const baskets = (n: number): string => t('baskets', { n });
