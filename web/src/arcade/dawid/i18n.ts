export const CATALOGS = { pl, en, de, sv };
export const t = translator<Key>(CATALOGS);
export type { Key };

/** A plural text without its number, for words set beside a number drawn on its own. */
export function bare(key: Key, n: number): string {
  return format(pick(CATALOGS[lang][key], n), { n: '' }).replace(/^[+\s ]+/, '').replace(/\s{2,}/g, ' ').trim();
}

/** The headline's unit: XP (EP in German); it does not bend. */
export const unit = (_n: number): string => t('unit');

/** A counted text with its number formatted in the language's style ("12 345 srebrników"), the form picked by the number. */
export function count(key: Key, n: number, extra?: Record<string, string | number>): string {
  const v = Math.round(n);
  return format(pick(CATALOGS[lang][key] ?? CATALOGS.pl[key], v), { ...extra, n: fmtNum(v) });
}

