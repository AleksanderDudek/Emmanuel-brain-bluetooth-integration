/**
 * The story of HolyHolyHoly 3D (Polish): a guardian angel and the person under its protection,
 * a man or a woman in today's Poland, chosen by the player (Adam or Ewa by default, after the
 * Anastasis icon, where Christ raises Adam and Eve by the wrist).
 *
 * Ten chapters climb the Ladder (St John Climacus' icon of the Ladder of Divine Ascent). Each one:
 * a situation of the 2020s built on what research says hurts men and women most (sources in
 * DESIGN.md), told in three stages of one day or night with memories found in the fight, the
 * shadow-thoughts it breeds and the voices that speak them, one lie personified (an allegorical
 * figure, as in Prudentius' Psychomachia), a Gospel encounter in which Christ comes to heal, a thought to transform (choose the balanced one, not the distorted
 * nor the sugar-coated), and one real skill to take into life.
 *
 * Christ is never playable, never a power: He comes, speaks His own words (Gdańsk Bible,
 * verbatim, with the reference) and the person answers. Text conventions: see game-data.mjs.
 */

// speakers: narrator, person ({imie}), angel (the player's archangel), christ, scripture
const N = (text, panel) => ({ who: 'narrator', text, ...(panel ? { panel } : {}) });
const P = text => ({ who: 'person', text });
const A = text => ({ who: 'angel', text });
const C = (ref, cut = {}) => ({ who: 'christ', verse: { ref, ...cut } });
const S = (ref, cut = {}, intro = '', panel) => ({ who: 'scripture', verse: { ref, ...cut }, text: intro, ...(panel ? { panel } : {}) });

/**
 * A stage of a chapter: one moment of the person's day or night. clock: [from, to] (HH:MM, the
 * clock runs while the stage lasts); sky: evening, dusk, night, deep (small hours) or day;
 * mod: '' or swarm (many weak shadows), heavy (fewer, stronger), dark (the fog closes in),
 * voices (the shadows speak more often). caption: what is happening now; memories: two
 * fragments of the story the angel finds on the map, from the everyday to the core wound.
 */
const stage = (clock, title, sky, mod, enemies, caption, memories) => ({ clock, title, sky, mod, enemies, caption, memories });
/**
 * A speaking shadow (Głos): the person's negative thought said aloud (says), the thinking error
 * it hides (pattern), what negates it (no: a fact, a distinction, a question answered) and the
 * balanced thought that rises in its place (yes). kind: the shadow that carries it.
 */
const voice = (kind, says, pattern, no, yes) => ({ kind, says, pattern, no, yes });

