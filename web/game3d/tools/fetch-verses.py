#!/usr/bin/env python3
"""
Generate web/game3d/tools/bible.mjs: the Scripture that only the 3D game quotes (the Gospel
encounters of the story, the archangels, the thought work). Same source, checks and rules as the
2D game's web/game/scripts/fetch_verses.py, which this script reuses: Biblia Gdańska (1881 edition,
public domain) from getbible.net, verified verse by verse against Polish Wikisource.

    python3 -I web/game3d/tools/fetch-verses.py [--data-dir DIR] [--offline] [--check]

Verses the 2D game already has (web/game/src/content/bible.ts) are taken from there; list here
only what is new.
"""
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE.parent.parent / "game" / "scripts" / "fetch_verses.py"

spec = importlib.util.spec_from_file_location("fetch_verses", SCRIPT)
fv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fv)

fv.REFS = [
    # Gospel encounters of the chapters
    "Mt 14,27", "Mk 10,14", "Mk 10,16", "Łk 19,5", "Mk 1,41", "J 5,6", "J 5,7", "Mk 5,34", "Łk 8,48",
    "Mt 26,52", "Łk 10,41", "Mk 5,15", "J 8,11", "J 11,25", "Łk 7,13", "Łk 24,29", "Łk 24,32",
    "Ef 5,14", "J 14,31", "Mt 28,20", "Mk 2,17", "Mt 9,36", "Łk 15,24",
    # the archangels
    "Dn 10,13", "Dn 12,1", "Ap 12,7", "Ap 12,10", "Ps 141,2", "1 Tes 5,17", "1 Tes 5,8", "2 Tm 4,7", "Ps 34,8",
    # thoughts and their truths
    "2 Kor 10,5", "Rz 12,2", "Flp 4,8", "Mt 6,34", "1 Sm 16,7", "Ps 139,14", "Ga 1,10", "Łk 12,7",
    "Rdz 2,18", "Koh 4,10", "Ps 68,7", "Iz 53,5", "Iz 61,1", "Rz 8,1", "Mt 5,4", "Ps 22,2",
    "Ps 42,6", "1 Krl 19,5", "Ps 23,4", "Iz 40,29", "Ps 127,2", "Mt 11,29", "1 Kor 10,13", "Ga 5,1",
    "Jr 29,11", "Jk 5,16", "Rz 12,21", "Ps 51,12", "1 J 1,9", "J 21,17", "2 Kor 1,4",
]


def render(bible: dict[str, str]) -> str:
    return "\n".join([
        "// Scripture quoted only by the 3D game. GENERATED by web/game3d/tools/fetch-verses.py; do not edit:",
        "// add the ref to REFS there and re-run it. Biblia Gdańska (1881 edition), public domain, from",
        f"// getbible.net ({fv.GETBIBLE_URL}), verified verse by verse against Polish Wikisource.",
        f"export const BIBLE3D = {json.dumps(bible, ensure_ascii=False, indent=1)};",
        "",
    ])


fv.OUT = HERE / "bible.mjs"
fv.render_ts = lambda bible, witnesses: render(bible)
if __name__ == "__main__":
    sys.argv[0] = str(Path(__file__).name)
    fv.main()
