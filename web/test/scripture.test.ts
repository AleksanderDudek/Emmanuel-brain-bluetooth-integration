import { describe, expect, it } from 'vitest';
import { drawPassage, layoutPassage, verseCard, wrapLines } from '../src/arcade/kit/scripture';
import { BIBLE_NAMES, passage, SCRIPTURE, type PassageId } from '../src/content/scripture';
import { LANGS } from '../src/i18n';

const ids = Object.keys(SCRIPTURE) as PassageId[];

// "Psalm 46:10", "Ps 46,11", "1. Mose 1,3", "1 Kung 19:12", "Lb 6,24–26"
const REF = /^(?:[1-5]\.? )?[\p{L}]+(?: [\p{L}]+)* \d{1,3}[,:]\d{1,3}(?:–\d{1,3})?$/u;

describe('scripture (generated by web/scripts/fetch_scripture.py)', () => {
  it('has every passage in all four languages, with a reference in the edition\'s own style', () => {
    expect(ids.length).toBeGreaterThan(50);
    for (const id of ids) {
      for (const l of LANGS) {
        const [text, ref] = SCRIPTURE[id][l];
        expect(text.length, `${id} ${l}`).toBeGreaterThan(10);
        expect(ref, `${id} ${l}`).toMatch(REF);
        expect(ref.includes(','), `${id} ${l} ${ref}`).toBe(l === 'pl' || l === 'de');
      }
    }
  });

  it('keeps quotation marks paired and never carries markup, notes or cross-references', () => {
    for (const id of ids) {
      for (const l of LANGS) {
        const [text] = SCRIPTURE[id][l];
        expect(text, `${id} ${l}`).not.toMatch(/[<>[\]{}\\\d]/);
        expect(text.split('“').length, `${id} ${l}: “ vs ”`).toBe(text.split('”').length);
        expect((text.match(/»/g) ?? []).length % 2, `${id} ${l}: »`).toBe(0);
        expect(text, `${id} ${l}`).toBe(text.trim());
      }
    }
  });

  it('numbers psalms as each edition does: a title is verse 1 in the Polish, German and Swedish Bibles', () => {
    expect(SCRIPTURE['psa46.10'].en[1]).toBe('Psalm 46:10');
    expect(SCRIPTURE['psa46.10'].pl[1]).toBe('Ps 46,11');
    expect(SCRIPTURE['psa46.10'].de[1]).toBe('Psalm 46,11');
    expect(SCRIPTURE['psa46.10'].sv[1]).toBe('Ps 46:11');
    // a short title stays inside verse 1 everywhere, and the quotation leaves it out
    expect(SCRIPTURE['psa23.1-3'].pl[1]).toBe('Ps 23,1–3');
    expect(SCRIPTURE['psa23.1-3'].en[0]).toMatch(/^The LORD is my shepherd/);
    expect(SCRIPTURE['psa19.1'].en[0]).toMatch(/^The heavens declare/);
  });

  it('gives a passage in the page\'s language (the tests run in Polish) or the one asked for', () => {
    expect(passage('psa46.10')).toEqual({ text: SCRIPTURE['psa46.10'].pl[0], ref: 'Ps 46,11', bible: BIBLE_NAMES.pl });
    expect(passage('mat5.14-16', 'en').bible).toBe('BSB');
    expect(passage('mat5.14-16', 'en').text).toMatch(/^You are the light of the world\./);
  });
});

describe('kit/scripture: verses on screen', () => {
  // a measuring context whose text width grows with the font size (enough to test the layout)
  const fakeCtx = () => {
    const c = {
      font: '12px x', textAlign: '', textBaseline: '', fillStyle: '', drawn: [] as string[],
      save() {}, restore() {},
      measureText(s: string) { return { width: s.length * Number(/(\d+)px/.exec(c.font)![1]) * 0.5 } as TextMetrics; },
      fillText(s: string) { c.drawn.push(s); },
    };
    return c;
  };

  it('wraps by words and never loses one', () => {
    const ctx = fakeCtx() as unknown as CanvasRenderingContext2D;
    ctx.font = '10px x';
    const lines = wrapLines(ctx, 'jeden dwa trzy cztery pięć sześć siedem', 60);
    expect(lines.join(' ')).toBe('jeden dwa trzy cztery pięć sześć siedem');
    expect(lines.every(l => l.length * 5 <= 60 || !l.includes(' '))).toBe(true);
  });

  it('shrinks the font until the passage and its reference fit, and cuts with "…" only when nothing fits', () => {
    const ctx = fakeCtx() as unknown as CanvasRenderingContext2D;
    const p = passage('mat5.14-16');
    const roomy = layoutPassage(ctx, p, 360, 600);
    expect(roomy.fits).toBe(true);
    expect(roomy.height).toBeLessThanOrEqual(600);
    const tight = layoutPassage(ctx, p, 360, 160);
    expect(tight.size).toBeLessThan(roomy.size);
    const tiny = layoutPassage(ctx, p, 120, 60, { min: 12 });
    expect(tiny.fits).toBe(false);
    expect(tiny.lines.at(-1)!.endsWith('…')).toBe(true);
    expect(tiny.height).toBeLessThanOrEqual(60 + tiny.lineH);
  });

  it('draws the verse and a reference line naming the edition', () => {
    const c = fakeCtx();
    const ctx = c as unknown as CanvasRenderingContext2D;
    const p = passage('psa46.10');
    drawPassage(ctx, p, layoutPassage(ctx, p, 300, 300), 150, 0, { text: '#fff', ref: '#aaa' });
    expect(c.drawn.at(-1)).toBe('Ps 46,11 · Biblia Gdańska');
    expect(c.drawn.slice(0, -1).join(' ')).toBe(p.text);
  });

  it('builds the summary card from the passage', () => {
    const el = verseCard('psa46.10');
    expect(el.tagName).toBe('FIGURE');
    expect(el.querySelector('blockquote')!.textContent).toBe(passage('psa46.10').text);
    expect(el.querySelector('figcaption')!.textContent).toBe('Ps 46,11 · Biblia Gdańska');
  });
});
