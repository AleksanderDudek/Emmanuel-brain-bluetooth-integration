import { describe, expect, it } from 'vitest';
import { LANGS } from '../src/i18n';
import { BIBLE_NAMES, passage, SCRIPTURE, type PassageId } from '../src/content/scripture';

const ids = Object.keys(SCRIPTURE) as PassageId[];

// "Psalm 46:10", "Ps 46,11", "1. Mose 1,3", "1 Kung 19:12", "Lb 6,24–26"
const REF = /^(?:[1-5]\.? )?[\p{L}]+(?: [\p{L}]+)* \d{1,3}[,:]\d{1,3}(?:–\d{1,3})?$/u;

describe('scripture (generated by web/scripts/fetch_scripture.py)', () => {
  it('has every passage in all four languages, with a reference in the edition\'s own style', () => {
    expect(ids.length).toBeGreaterThan(50);
    for (const id of ids) {
      for (const l of LANGS) {
        const [text, ref] = SCRIPTURE[id][l];
        expect(text.length, `${id} ${l}`).toBeGreaterThan(10);
        expect(ref, `${id} ${l}`).toMatch(REF);
        expect(ref.includes(',') , `${id} ${l} ${ref}`).toBe(l === 'pl' || l === 'de');
      }
    }
  });

  it('keeps quotation marks paired and never carries markup, notes or cross-references', () => {
    for (const id of ids) {
      for (const l of LANGS) {
        const [text] = SCRIPTURE[id][l];
        expect(text, `${id} ${l}`).not.toMatch(/[<>[\]{}\\\d]/);
        expect(text.split('“').length, `${id} ${l}: “ vs ”`).toBe(text.split('”').length);
        expect((text.match(/»/g) ?? []).length % 2, `${id} ${l}: »`).toBe(0);
        expect(text, `${id} ${l}`).toBe(text.trim());
      }
    }
  });

  it('numbers psalms as each edition does: a title is verse 1 in the Polish, German and Swedish Bibles', () => {
    expect(SCRIPTURE['psa46.10'].en[1]).toBe('Psalm 46:10');
    expect(SCRIPTURE['psa46.10'].pl[1]).toBe('Ps 46,11');
    expect(SCRIPTURE['psa46.10'].de[1]).toBe('Psalm 46,11');
    expect(SCRIPTURE['psa46.10'].sv[1]).toBe('Ps 46:11');
    // a short title stays inside verse 1 everywhere, and the quotation leaves it out
    expect(SCRIPTURE['psa23.1-3'].pl[1]).toBe('Ps 23,1–3');
    expect(SCRIPTURE['psa23.1-3'].en[0]).toMatch(/^The LORD is my shepherd/);
    expect(SCRIPTURE['psa19.1'].en[0]).toMatch(/^The heavens declare/);
  });

  it('gives a passage in the page\'s language (the tests run in Polish) or the one asked for', () => {
    expect(passage('psa46.10')).toEqual({ text: SCRIPTURE['psa46.10'].pl[0], ref: 'Ps 46,11', bible: BIBLE_NAMES.pl });
    expect(passage('mat5.14-16', 'en').bible).toBe('BSB');
    expect(passage('mat5.14-16', 'en').text).toMatch(/^You are the light of the world\./);
  });
});
